/**
 * حساب الكثافة المصححة عند 60/60°F من درجة الحرارة المقروءة بالفهرنهايت وكثافة الهايدروميتر
 */
export function calculateCorrectedGravity(
  tempF: number,
  observedGravity: number
): CorrectionResult {
  const temps = Object.keys(FULL_DENSITY_TABLE)
    .map(Number)
    .sort((a, b) => a - b);
  const minTemp = temps[0]; // 0
  const maxTemp = temps[temps.length - 1]; // 100

  const minGravity = OBSERVED_GRAVITIES[0]; // 0.505
  const maxGravity = OBSERVED_GRAVITIES[OBSERVED_GRAVITIES.length - 1]; // 0.600

  const roundTemp = Math.round(tempF);
  const matchedGravIdx = OBSERVED_GRAVITIES.findIndex(
    (g) => Math.abs(g - observedGravity) < 0.0001
  );

  let isExact = false;
  let correctedVal: number;

  // فحص ما إذا كانت الخلية متطابقة تماماً وموجودة في الجدول
  if (
    tempF === roundTemp &&
    roundTemp in FULL_DENSITY_TABLE &&
    matchedGravIdx !== -1 &&
    FULL_DENSITY_TABLE[roundTemp][matchedGravIdx] !== null
  ) {
    correctedVal = FULL_DENSITY_TABLE[roundTemp][matchedGravIdx]!;
    isExact = true;
  } else {
    // إجراء استيفاء ثنائي خطي (Bilinear Interpolation)
    const clampedTemp = Math.max(minTemp, Math.min(maxTemp, tempF));
    const t0 = Math.floor(clampedTemp);
    const t1 = Math.ceil(clampedTemp);
    const tRatio = t1 === t0 ? 0 : (clampedTemp - t0) / (t1 - t0);

    const clampedGrav = Math.max(minGravity, Math.min(maxGravity, observedGravity));
    let g0Idx = 0;
    while (
      g0Idx < OBSERVED_GRAVITIES.length - 1 &&
      OBSERVED_GRAVITIES[g0Idx + 1] <= clampedGrav
    ) {
      g0Idx++;
    }
    const g1Idx = Math.min(g0Idx + 1, OBSERVED_GRAVITIES.length - 1);

    const g0 = OBSERVED_GRAVITIES[g0Idx];
    const g1 = OBSERVED_GRAVITIES[g1Idx];
    const gRatio = g1 === g0 ? 0 : (clampedGrav - g0) / (g1 - g0);

    const row0 = FULL_DENSITY_TABLE[t0] || FULL_DENSITY_TABLE[minTemp];
    const row1 = FULL_DENSITY_TABLE[t1] || FULL_DENSITY_TABLE[maxTemp];

    // التعامل مع القيم الفارغة في نطاقات التجمد للبروبان
    const getVal = (row: TableRow, gIdx: number, t: number): number => {
      const val = row[gIdx];
      if (val !== null) return val;
      // استكمال افتراضي بمعامل التمدد الحراري
      const baseRow = FULL_DENSITY_TABLE[50] || FULL_DENSITY_TABLE[60];
      const baseVal = baseRow[gIdx] ?? OBSERVED_GRAVITIES[gIdx];
      return baseVal - (60 - t) * 0.00075;
    };

    const v00 = getVal(row0, g0Idx, t0);
    const v01 = getVal(row0, g1Idx, t0);
    const v10 = getVal(row1, g0Idx, t1);
    const v11 = getVal(row1, g1Idx, t1);

    const v_g0 = v00 + tRatio * (v10 - v00);
    const v_g1 = v01 + tRatio * (v11 - v01);

    let interpVal = v_g0 + gRatio * (v_g1 - v_g0);

    // إذا كانت القيمة خارج حدود الجدول (أقل من 0°F أو أكثر من 100°F أو خارج 0.505-0.600)
    if (tempF < minTemp || tempF > maxTemp || observedGravity < minGravity || observedGravity > maxGravity) {
      const tempDiff = tempF - clampedTemp;
      const gravDiff = observedGravity - clampedGrav;
      interpVal += tempDiff * 0.00075 + gravDiff * 0.98;
    }

    correctedVal = interpVal;
  }

  // إيجاد أقرب خلية معرفة في الجدول المرجعي
  let closestTemp = minTemp;
  let minTDiff = Infinity;
  for (const t of temps) {
    if (Math.abs(t - tempF) < minTDiff) {
      minTDiff = Math.abs(t - tempF);
      closestTemp = t;
    }
  }

  let closestGrav: number = OBSERVED_GRAVITIES[0];
  let minGDiff = Infinity;
  let closestIdx = 0;
  OBSERVED_GRAVITIES.forEach((g, idx) => {
    if (Math.abs(g - observedGravity) < minGDiff) {
      minGDiff = Math.abs(g - observedGravity);
      closestGrav = g;
      closestIdx = idx;
    }
  });

  const rawTableVal = FULL_DENSITY_TABLE[closestTemp][closestIdx];
  const tableValue = rawTableVal ?? Number(correctedVal.toFixed(4));
  const delta = Number((correctedVal - observedGravity).toFixed(4));

  const isWithinTableRange =
    tempF >= minTemp &&
    tempF <= maxTemp &&
    observedGravity >= minGravity &&
    observedGravity <= maxGravity &&
    rawTableVal !== null;

  return {
    observedTempF: tempF,
    observedGravity,
    correctedGravity: Number(correctedVal.toFixed(4)),
    isExactMatch: isExact,
    delta,
    closestTemp,
    closestGravity: closestGrav,
    tableValue,
    isWithinTableRange,
  };
}

/**
 * تحويل الوحدات بين الطن والكيلوغرام
 */
export function tonsToKg(tons: number): number {
  return tons * 1000;
}

export function kgToTons(kg: number): number {
  return kg / 1000;
}

/**
 * حساب الوزن من الحجم باللتر والكثافة (طن وكيلوغرام)
 */
export function calculateWeightFromVolume(liters: number, density: number) {
  const kg = liters * density;
  const tons = kg / 1000;
  return { kg, tons };
}

/**
 * حساب الحجم باللتر من الوزن بالكيلوغرام والكثافة
 */
export function calculateVolumeFromWeight(kg: number, density: number) {
  if (density <= 0) return 0;
  return kg / density;
}
